// Setzt die Abschnitte eines Levels zu Zeilen zusammen.
function buildLevelRows(def) {
  const rows = [];
  for (let y = 0; y < LEVEL_H; y++) rows.push('');
  def.chunks.forEach((chunk, ci) => {
    const lines = chunk.split('\n').filter((l) => l.length > 0);
    const w = lines[0].length;
    lines.forEach((l, li) => {
      if (l.length !== w) {
        throw new Error(`Level "${def.id}", Abschnitt ${ci + 1}, Zeile ${li + 1}: Breite ${l.length} statt ${w}`);
      }
    });
    if (lines.length > LEVEL_H) throw new Error(`Level "${def.id}", Abschnitt ${ci + 1}: zu hoch`);
    const pad = LEVEL_H - lines.length;
    for (let y = 0; y < LEVEL_H; y++) rows[y] += y < pad ? '.'.repeat(w) : lines[y - pad];
  });
  return rows;
}

